// Engineering report generator: HTML preview → PDF (print), DOCX, XLSX, CSV, JSON.
import { h, selectField, toast, download, table, kv } from '../dom.js';
import { modelById, STATUS_LABEL } from '../../core/models.js';
import { VERSION } from '../../core/version.js';
import { DocxBuilder } from '../../research/docx.js';
import { toCSV } from '../../research/stats.js';
import { settings } from '../dom.js';

/** Generic methodology, used by workspaces that do not supply their own (report().method). */
const METHOD = 'MachinaSim advances the process one spindle (or cutter) revolution at a time. Each revolution: (1) the tool outline is positioned along the planned path; (2) the engaged leading cutting edge and the removed chip section are computed from the current workpiece geometry; (3) the geometry is updated (exact axisymmetric profile for lathe work, Z-map height field for prismatic work); (4) forces follow from the chip section and engaged edge length via the Kienzle law with rake correction and friction-angle thrust ratio, plus flank-wear-land forces; (5) torque, power and MRR follow from forces, kinematics and the removed volume; (6) reduced-order temperatures and the FD tool field are updated; (7) tool wear advances (Taylor–Miner) and feeds back into forces and tool-nose position.';

export class ReportsPage {
  constructor(root, app) {
    this.app = app;
    this.s = { src: 'lathe', title: '', objective: '', conclusions: '', validation: '' };
    this.srcSel = selectField(this.s, 'src', [], { label: 'Workspace', onChange: () => this.build() });
    const ta = (k, label, rows = 3) => { const t = h('textarea', { rows, oninput: (e) => { this.s[k] = e.target.value; this.build(true); } }); t.value = this.s[k]; this[`ta_${k}`] = t; return h('div', { class: 'field' }, h('label', {}, label), t); };
    this.preview = h('article', { id: 'report-preview', class: 'box report' });
    this.tTitle = h('input', { type: 'text', oninput: (e) => { this.s.title = e.target.value; this.build(true); } });
    const inputs = h('div', { class: 'box' }, this.srcSel, h('div', { class: 'field' }, h('label', {}, 'Title'), this.tTitle),
      ta('objective', 'Objective'), ta('validation', 'Experimental validation summary (enter measured comparisons — leave empty if none)'), ta('conclusions', 'Conclusions (pre-filled with factual result statements — edit)', 5));
    const btn = (label, fn, cls = 'btn') => h('button', { class: cls, type: 'button', onclick: fn }, label);
    const exports = h('div', { class: 'box' },
      h('div', { class: 'row' }, btn('Refresh from workspace', () => this.build(), 'btn primary'), btn('PDF (print)', () => this.pdf()), btn('DOCX', () => this.docx()), btn('XLSX', () => this.xlsx()), btn('CSV data', () => this.csv()), btn('JSON', () => this.json())),
      h('p', { class: 'note' }, 'PDF: use the browser print dialog → “Save as PDF”. Only the report is printed.'));
    root.append(h('div', { class: 'content' }, h('h1', {}, 'Engineering reports'),
      h('p', { class: 'lead' }, 'Reports are assembled from the current state of a workspace. All result values are SIMULATED unless explicitly entered as measured. Model status and limitations are included automatically.'),
      h('div', { class: 'two noprint' }, inputs, exports),
      this.preview));
  }
  show() {
    const opts = Object.entries(this.app.pages).filter(([, p]) => p.report).map(([k]) => ({ value: k, label: this.app.routes.find((r) => r.id === k)?.label || k }));
    if (!opts.length) { this.preview.replaceChildren(h('p', { class: 'muted' }, 'Open a machine workspace (Lathe, Radial drill, Milling, …), run a simulation, then return here.')); return; }
    if (!opts.find((o) => o.value === this.s.src)) this.s.src = opts[0].value;
    this.srcSel.setOptions(opts);
    this.build();
  }
  data() {
    const p = this.app.pages[this.s.src];
    if (!p?.report) return null;
    try { return p.report(); } catch (e) { toast(`Report failed: ${e.message}`, 'error'); return null; }
  }
  build(keepText = false) {
    const r = keepText && this._r ? this._r : this.data();
    if (!r) return;
    this._r = r;
    if (!keepText) {
      if (!this.s.title) { this.s.title = r.title; this.tTitle.value = r.title; }
      const auto = r.results.map(([k, v]) => `Simulated ${k.toLowerCase()}: ${typeof v === 'string' ? v : v?.textContent ?? v}.`).join(' ');
      this.s.conclusions = auto; this.ta_conclusions.value = auto;
    }
    const models = (r.models || []).map(modelById).filter(Boolean);
    const sec = (n, t, ...c) => h('section', {}, h('h2', {}, `${n}. ${t}`), ...c);
    const imgs = (r.charts || []).map((c) => ({ url: c.toDataURL(), title: c.o.title }));
    this.preview.replaceChildren(
      h('h1', {}, this.s.title || r.title),
      h('p', { class: 'muted' }, `Generated by MachinaSim v${VERSION} (model version ${VERSION}) on ${new Date().toLocaleString()} · units: ${settings.units}`),
      sec(1, 'Objective', h('p', {}, this.s.objective || '—')),
      sec(2, 'Machine', h('p', {}, r.machine)), sec(3, 'Workpiece', h('p', {}, r.workpiece)), sec(4, 'Tool', h('p', {}, r.tool)),
      sec(5, 'Machining parameters', r.params?.length ? h('ul', {}, r.params.map((x) => h('li', {}, x))) : h('p', {}, '—')),
      sec(6, 'Mathematical models', table(['ID', 'Model', 'Equation', 'Status'], models.map((m) => [m.id, m.name, m.eq, STATUS_LABEL[m.status]]))),
      sec(7, 'Assumptions', h('ul', {}, models.map((m) => h('li', {}, `${m.id}: ${m.assumptions}`)))),
      sec(8, 'Calculation methodology', ...(r.method || [METHOD]).map((x) => h('p', {}, x))),
      sec(9, 'Results (simulated)', kv(r.results)),
      sec(10, 'Graphs', ...imgs.map((i) => h('figure', {}, h('img', { src: i.url, style: { maxWidth: '100%' } }), h('figcaption', {}, i.title)))),
      sec(11, '3-D simulation image', r.snapshot ? h('img', { src: r.snapshot, style: { maxWidth: '100%' } }) : h('p', { class: 'muted' }, 'Not available'), ...(r.images || []).map((u) => h('img', { src: u, style: { maxWidth: '100%' } }))),
      sec(12, 'Experimental validation', h('p', {}, this.s.validation || 'No experimental data compared in this report. Model predictions are not validated for these conditions.')),
      sec(13, 'Conclusions', h('p', {}, this.s.conclusions)),
      sec(14, 'Limitations', h('ul', {}, [...(r.limitations || []), ...models.map((m) => `${m.id} validity: ${m.validity}`)].map((x) => h('li', {}, x)))),
    );
    this._imgs = imgs;
  }
  pdf() { if (!this._r) return toast('Nothing to print', 'warn'); document.body.classList.add('print-report'); window.print(); setTimeout(() => document.body.classList.remove('print-report'), 500); }
  docx() {
    const r = this._r; if (!r) return toast('Build a report first', 'warn');
    const d = new DocxBuilder();
    const models = (r.models || []).map(modelById).filter(Boolean);
    d.heading(this.s.title || r.title, 1).para(`Generated by MachinaSim v${VERSION} on ${new Date().toLocaleString()}`, { italic: true });
    d.heading('1. Objective', 2).para(this.s.objective || '—');
    d.heading('2. Machine', 2).para(r.machine).heading('3. Workpiece', 2).para(r.workpiece).heading('4. Tool', 2).para(r.tool);
    d.heading('5. Machining parameters', 2); (r.params?.length ? r.params : ['—']).forEach((x) => d.para(`• ${x}`));
    d.heading('6. Mathematical models', 2).table(['ID', 'Model', 'Equation', 'Status'], models.map((m) => [m.id, m.name, m.eq, STATUS_LABEL[m.status]]));
    d.heading('7. Assumptions', 2); models.forEach((m) => d.para(`• ${m.id}: ${m.assumptions}`));
    d.heading('8. Calculation methodology', 2); (r.method || [METHOD]).forEach((x) => d.para(x));
    d.heading('9. Results (simulated)', 2).table(['Quantity', 'Value'], r.results.map(([k, v]) => [k, typeof v === 'string' ? v : v?.textContent ?? String(v)]));
    d.heading('10. Graphs', 2);
    (r.charts || []).forEach((c) => { const u = c.toDataURL(); d.image(u, c.canvas.width / (window.devicePixelRatio || 1), c.canvas.height / (window.devicePixelRatio || 1)).para(c.o.title || '', { italic: true }); });
    if (r.snapshot) { d.heading('11. 3-D simulation image', 2); const im = new Image(); im.src = r.snapshot; d.image(r.snapshot, 800, 500); }
    d.heading('12. Experimental validation', 2).para(this.s.validation || 'No experimental data compared in this report.');
    d.heading('13. Conclusions', 2).para(this.s.conclusions || '—');
    d.heading('14. Limitations', 2); [...(r.limitations || []), ...models.map((m) => `${m.id} validity: ${m.validity}`)].forEach((x) => d.para(`• ${x}`));
    download(`${(this.s.title || r.title).replace(/\W+/g, '_')}.docx`, new Blob([d.build()], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }));
  }
  async xlsx() {
    const r = this._r; if (!r) return toast('Build a report first', 'warn');
    if (!window.XLSX) await new Promise((res, rej) => { const s = document.createElement('script'); s.src = 'vendor/xlsx.mini.min.js'; s.onload = res; s.onerror = () => rej(new Error('XLSX library failed to load')); document.head.append(s); });
    const X = window.XLSX, wb = X.utils.book_new();
    X.utils.book_append_sheet(wb, X.utils.aoa_to_sheet([['Quantity', 'Value (simulated)'], ...r.results.map(([k, v]) => [k, typeof v === 'string' ? v : v?.textContent ?? String(v)])]), 'Results');
    if (r.data) X.utils.book_append_sheet(wb, X.utils.aoa_to_sheet([r.data.headers, ...r.data.rows]), 'Time history');
    X.utils.book_append_sheet(wb, X.utils.aoa_to_sheet([['ID', 'Model', 'Equation', 'Status', 'Validity'], ...(r.models || []).map(modelById).filter(Boolean).map((m) => [m.id, m.name, m.eq, STATUS_LABEL[m.status], m.validity])]), 'Models');
    const out = X.write(wb, { type: 'array', bookType: 'xlsx' });
    download(`${(this.s.title || r.title).replace(/\W+/g, '_')}.xlsx`, new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }));
  }
  csv() { const r = this._r; if (!r?.data) return toast('No time-history data', 'warn'); download(`${(this.s.title || r.title).replace(/\W+/g, '_')}.csv`, toCSV(r.data.headers, r.data.rows), 'text/csv'); }
  json() { const r = this._r; if (!r) return; download('report.json', JSON.stringify({ ...r, charts: undefined, snapshot: undefined, version: VERSION, title: this.s.title, objective: this.s.objective, conclusions: this.s.conclusions, results: r.results.map(([k, v]) => [k, typeof v === 'string' ? v : v?.textContent ?? String(v)]) }, null, 1), 'application/json'); }
}
